function solar(
  Outline: (props: SolarProps) => React.ReactNode,
  Filled: (props: SolarProps) => React.ReactNode,
): IconComponent {
  return forwardRef<SVGSVGElement, IconProps>(({ filled, ...props }, ref) => {
    const Glyph = filled ? Filled : Outline;
    return <Glyph ref={ref} {...props} />;
  });
}
